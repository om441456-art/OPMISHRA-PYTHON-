# ---------------- FUNCTIONS ----------------
def move(x, y):
    t.penup()
    t.goto(x, y)
    t.pendown()

def polygon(points, fill, outline=None, width=2):
    t.penup()
    t.goto(points[0])
    t.pendown()

    if outline:
        t.color(outline)
    else:
        t.color(fill)

    t.begin_fill()
    for p in points[1:]:
        t.goto(p)
    t.goto(points[0])
    t.end_fill()

def circle(x, y, r, color):
    t.penup()
    t.goto(x, y-r)
    t.setheading(0)
    t.color(color)
    t.begin_fill()
    t.circle(r)
    t.end_fill()

def line(points, color, width=4):
    t.color(color)
    t.pensize(width)
    move(*points[0])

    for p in points[1:]:
        t.goto(*p)

