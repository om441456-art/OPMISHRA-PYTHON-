# ================= FUNCTIONS =================

def move(x, y):
    t.penup()
    t.goto(x, y)
    t.pendown()


def draw_line(points, color="#00BFFF", width=3):
    t.penup()
    t.goto(points[0])
    t.pendown()

    t.color(color)
    t.pensize(width)

    for point in points[1:]:
        t.goto(point)


def glow_line(points):
    # Outer glow
    draw_line(points, "#003B73", 10)

    # Middle glow
    draw_line(points, "#0066CC", 6)

    # Bright line
    draw_line(points, "#00D9FF", 2)


def circle_outline(x, y, radius):
    # Glow
    t.color("#003B73")
    t.pensize(9)
    move(x + radius, y)

    for i in range(361):
        a = math.radians(i)
        t.goto(
            x + radius * math.cos(a),
            y + radius * math.sin(a)
        )

    # Bright outline
    t.color("#00D9FF")
    t.pensize(2)
    move(x + radius, y)

    for i in range(361):
        a = math.radians(i)
        t.goto(
            x + radius * math.cos(a),
            y + radius * math.sin(a)
        )


